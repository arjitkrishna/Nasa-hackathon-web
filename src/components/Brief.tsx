import { useState, type ReactNode } from "react";
import { HABITATS, type HabitatOption } from "./Habitat";
import type { Experiment, RankedExperiment } from "../types";

type Audience = "student" | "engineer" | "researcher";

const AUDIENCES: { id: Audience; label: string; note: string }[] = [
  { id: "student", label: "Student", note: "Plain-language summary and what it means for crews." },
  { id: "engineer", label: "Engineer", note: "Test setup, design implications and limits." },
  { id: "researcher", label: "Researcher", note: "Findings, original figures, limits and open questions." },
];

interface Section {
  heading: string;
  lines: string[]; // lines starting with "- " are bullets
}

function rangeText(min: number | undefined, max: number | undefined, unit: string): string {
  if (min === undefined && max === undefined) return "not reported";
  if (min !== undefined && max !== undefined) return min === max ? `${min} ${unit}` : `${min} to ${max} ${unit}`;
  if (max !== undefined) return `up to ${max} ${unit}`;
  return `from ${min} ${unit}`;
}

function fitLine(name: string, target: number, unit: string, min: number | undefined, max: number | undefined): string {
  if (min === undefined && max === undefined) return `- ${name}: not reported in this atlas.`;
  const low = min ?? (max as number);
  const high = max ?? (min as number);
  const tested = rangeText(min, max, unit);
  if (target >= low && target <= high) {
    return `- ${name}: tested ${tested}, which includes the habitat's ${target} ${unit}.`;
  }
  const off = Math.round((target < low ? low - target : target - high) * 100) / 100;
  return `- ${name}: tested ${tested}, which is ${off} ${unit} away from the habitat's ${target} ${unit}.`;
}

function buildSections(list: Experiment[], habitat: HabitatOption, audience: Audience): Section[] {
  const who = AUDIENCES.find((item) => item.id === audience)?.label.toLowerCase() ?? "general";
  const sections: Section[] = [];

  sections.push({
    heading: "Purpose",
    lines: [
      `This brief summarizes ${list.length} NASA microgravity combustion investigation${list.length === 1 ? "" : "s"} for fire safety in a ${habitat.label.toLowerCase()}. It is written for a ${who} audience.`,
      `Habitat conditions used for matching: ${habitat.oxygen}% oxygen at ${habitat.pressure} atm. ${habitat.note}`,
    ],
  });

  for (const e of list) {
    const lines: string[] = [
      e.summary,
      `Status: ${e.status.replace("-", " ")}. Platform: ${e.platform}. Domain: ${e.domain}.`,
      "Fit to this habitat:",
      fitLine("Oxygen", habitat.oxygen, "%", e.conditions.oxygenMin, e.conditions.oxygenMax),
      fitLine("Pressure", habitat.pressure, "atm", e.conditions.pressureMin, e.conditions.pressureMax),
    ];

    if (audience === "student") {
      lines.push(`What it means: ${e.meaning}`);
      if (e.insight) lines.push(`For crews (an interpretation, not a NASA statement): ${e.insight.crew}`);
    } else if (audience === "engineer") {
      if (e.insight) lines.push(`For design (an interpretation, not a NASA statement): ${e.insight.design}`);
      const setup = [
        e.fuel ? `- Fuel: ${e.fuel}` : "",
        e.hardware ? `- Hardware: ${e.hardware}` : "",
        e.measurements ? `- Measurements: ${e.measurements}` : "",
      ].filter((line) => line !== "");
      if (setup.length > 0) lines.push("Test setup:", ...setup);
      lines.push("Limits:", ...e.limits.map((limit) => `- ${limit}`));
    } else {
      lines.push("Findings:", ...e.findings.map((finding) => `- ${finding}`));
      if (e.original.length > 0) {
        lines.push("Original figures:", ...e.original.map((row) => `- ${row.label}: ${row.value}`));
      }
      lines.push("Limits:", ...e.limits.map((limit) => `- ${limit}`));
      lines.push("Still open:", ...e.openQuestions.map((question) => `- ${question}`));
    }

    sections.push({ heading: `${e.name} (${e.years})`, lines });
  }

  sections.push({
    heading: "Gaps to keep in mind",
    lines: [
      "- Every experiment here ran in microgravity. The 2026 NASA Space Apps challenge description states that NASA's PSI database currently has no partial-gravity combustion data, so lunar and Martian gravity are not covered.",
      "- A match on oxygen and pressure does not prove a habitat is safe. A test may not have combined both conditions at once.",
      "- Entries marked as interpretations are this atlas's reading of the findings, not NASA statements.",
    ],
  });

  sections.push({
    heading: "Sources",
    lines: list.flatMap((e) => e.sources.map((source) => `- ${e.name}: ${source.label} (${source.url})`)),
  });

  sections.push({
    heading: "About this brief",
    lines: [
      `Generated by the Orrery NASA fire safety atlas on ${new Date().toLocaleDateString()}. Scores and tags are the atlas author's judgment. Check the sources before relying on any figure.`,
    ],
  });

  return sections;
}

function toMarkdown(title: string, sections: Section[]): string {
  const parts: string[] = [`# ${title}`];
  for (const section of sections) {
    let body = "";
    section.lines.forEach((line, index) => {
      const bullet = line.startsWith("- ");
      const previousBullet = index > 0 && section.lines[index - 1].startsWith("- ");
      body += index === 0 ? "" : bullet && previousBullet ? "\n" : "\n\n";
      body += line;
    });
    parts.push(`## ${section.heading}\n\n${body}`);
  }
  return `${parts.join("\n\n")}\n`;
}

function renderLines(lines: string[]): ReactNode[] {
  const nodes: ReactNode[] = [];
  let bullets: string[] = [];
  const flush = () => {
    if (bullets.length > 0) {
      const items = bullets;
      nodes.push(
        <ul key={`list-${nodes.length}`}>
          {items.map((item, index) => (
            <li key={index}>{item}</li>
          ))}
        </ul>,
      );
      bullets = [];
    }
  };
  lines.forEach((line, index) => {
    if (line.startsWith("- ")) {
      bullets.push(line.slice(2));
    } else {
      flush();
      nodes.push(<p key={`text-${index}`}>{line}</p>);
    }
  });
  flush();
  return nodes;
}

interface BriefProps {
  entries: RankedExperiment[];
  pinned: RankedExperiment[];
}

export function Brief({ entries, pinned }: BriefProps) {
  const [habitatId, setHabitatId] = useState("moon");
  const [audience, setAudience] = useState<Audience>("engineer");
  const [copied, setCopied] = useState(false);

  const habitats = HABITATS.filter((option) => option.id !== "custom");
  const habitat = habitats.find((option) => option.id === habitatId) ?? habitats[0];
  const usingPins = pinned.length > 0;
  const chosen = (usingPins ? pinned : entries.slice(0, 3)).map((entry) => entry.experiment);
  const title = `Fire safety brief: ${habitat.label}`;
  const sections = buildSections(chosen, habitat, audience);
  const markdown = toMarkdown(title, sections);

  async function copyBrief() {
    await navigator.clipboard.writeText(markdown);
    setCopied(true);
    window.setTimeout(() => setCopied(false), 1600);
  }

  function downloadBrief() {
    const blob = new Blob([markdown], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "fire-safety-brief.md";
    link.click();
    URL.revokeObjectURL(url);
  }

  return (
    <div className="brief">
      <div className="brief-controls">
        <div>
          <p className="brief-label">Habitat</p>
          <div className="presets">
            {habitats.map((option) => (
              <button
                key={option.id}
                type="button"
                className={option.id === habitatId ? "chip is-on" : "chip"}
                onClick={() => setHabitatId(option.id)}
              >
                {option.label}
              </button>
            ))}
          </div>
        </div>
        <div>
          <p className="brief-label">Audience</p>
          <div className="presets">
            {AUDIENCES.map((item) => (
              <button
                key={item.id}
                type="button"
                className={item.id === audience ? "chip is-on" : "chip"}
                onClick={() => setAudience(item.id)}
              >
                {item.label}
              </button>
            ))}
          </div>
          <p className="brief-source-note">{AUDIENCES.find((item) => item.id === audience)?.note}</p>
        </div>
        <p className="brief-source-note">
          {usingPins
            ? `Using your ${pinned.length} pinned experiment${pinned.length === 1 ? "" : "s"}.`
            : "No experiments are pinned, so this uses the top 3 from your current ranking. Pin experiments in Compare or in a list to choose your own."}
        </p>
      </div>

      {chosen.length === 0 ? (
        <p className="quiet">No experiments match your current filters. Clear the filters or pin an experiment.</p>
      ) : (
        <>
          <div className="brief-actions">
            <button type="button" className="chip" onClick={copyBrief}>
              {copied ? "Copied" : "Copy brief"}
            </button>
            <button type="button" className="chip" onClick={downloadBrief}>
              Download (.md)
            </button>
            <button type="button" className="chip" onClick={() => window.print()}>
              Print or save as PDF
            </button>
          </div>

          <article className="brief-sheet">
            <h2>{title}</h2>
            {sections.map((section) => (
              <section key={section.heading}>
                <h3>{section.heading}</h3>
                {renderLines(section.lines)}
              </section>
            ))}
          </article>
        </>
      )}
    </div>
  );
}